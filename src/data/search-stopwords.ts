/**
 * キーワード検索の分割語・不要語
 *
 * 日本語は分かち書きしないため、「9号館でやってるダンスのやつ」のような文章クエリを
 * そのまま部分一致に掛けると必ず0件になります。ここに並べた語を「区切り」と「捨てる語」の
 * 両方に使い、文章から検索語だけを取り出します。
 *
 * **値はすべて `normalizeText()` を通した形（ひらがな・小文字・記号なし）で書いてください。**
 * 照合前に正規化されるため、`ダンス` ではなく `だんす` が実際の比較対象になります。
 */

/**
 * 助詞
 *
 * 語と語の境界としてのみ使います。**1〜2文字の語は、左側に2文字以上を残せるときだけ
 * 区切りとして働きます。** この制限が無いと `のど自慢` が `ど自慢` に割れます。
 */
export const searchParticles: string[] = [
  "の",
  "が",
  "を",
  "は",
  "で",
  "に",
  "へ",
  "と",
  "や",
  "も",
  "から",
  "まで",
  "って",
  "という",
];

/**
 * 検索語として意味を持たない語
 *
 * 区切りとしても、切り出したあとに捨てる語としても使います。
 *
 * **3文字以上の語は先頭からでも区切れます**（`やってるだんす` → `だんす`）。
 * 3文字も続けて一致する語が別の単語の一部である可能性は低く、`のど自慢` のような
 * 事故が起きないためです。
 *
 * **全トークンがここに載っていた場合、`tokenizeQuery()` は空配列を返します。** これは
 * 「0件」ではなく「絞り込む条件が無い」という意味で、`searchEvents()` がそのとき全件を
 * 返します。「企画」だけで検索した来場者に0件を返さないためです。捨てたトークンを
 * 復元する処理はありません（`src/lib/search.ts` の `searchEvents` を参照）。
 *
 * なお `企画` のように**実際に一致する語**なら、トークン化より先に段1（クエリ全体の
 * 部分一致）が拾うので、そもそもここまで落ちてきません。
 */
export const searchStopwords: string[] = [
  // 企画一覧そのものを指す語（絞り込みに寄与しない）
  "企画",
  "いべんと",
  "だしもの",
  "ぷろぐらむ",
  // 依頼・疑問の言い回し
  "おすすめ",
  "おしえて",
  "教えて",
  "知りたい",
  "しりたい",
  "見たい",
  "みたい",
  "探して",
  "さがして",
  "ください",
  "どこ",
  "いつ",
  "なに",
  "何",
  "どれ",
  "ある",
  "あります",
  "ますか",
  "ですか",
  // 口語の言い回し
  "やってる",
  "やっている",
  "してる",
  "している",
  "やつ",
  "もの",
  "こと",
];
